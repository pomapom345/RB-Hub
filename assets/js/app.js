  function parseRoute() {
    var raw = location.hash.replace(/^#/, '');
    if (!raw) raw = '/';

    var anchor = '';
    var hashIndex = raw.indexOf('#');
    if (hashIndex !== -1) {
      anchor = raw.slice(hashIndex + 1);
      raw = raw.slice(0, hashIndex);
    }

    var query = {};
    var queryIndex = raw.indexOf('?');
    if (queryIndex !== -1) {
      var qs = raw.slice(queryIndex + 1);
      raw = raw.slice(0, queryIndex);
      try {
        new URLSearchParams(qs).forEach(function (value, key) { query[key] = value; });
      } catch (err) { /* ignore malformed query strings */ }
    }

    var segs = raw.split('/').filter(Boolean);
    return { path: '/' + segs.join('/'), segs: segs, query: query, anchor: anchor };
  }

