  var SORTERS = {
    'title-asc': function (a, b) { return collate(a.title, b.title); },
    'title-desc': function (a, b) { return collate(b.title, a.title); },
    'year-asc': function (a, b) {
      if (!a.year && !b.year) return collate(a.title, b.title);
      if (!a.year) return 1;
      if (!b.year) return -1;
      return (a.year - b.year) || collate(a.title, b.title);
    },
    'year-desc': function (a, b) {
      if (!a.year && !b.year) return collate(a.title, b.title);
      if (!a.year) return 1;
      if (!b.year) return -1;
      return (b.year - a.year) || collate(a.title, b.title);
    },
    'platform-asc': function (a, b) {
      return collate(a.platformName, b.platformName) || collate(a.title, b.title);
    }
  };

