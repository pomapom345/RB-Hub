  function searchBlob(g) {
    if (g._blob) return g._blob;
    var parts = [g.title, g.platformName, g.genre, g.developer, g.publisher, g.id];
    (g.variants || []).forEach(function (v) {
      parts.push(v.fileName, v.file, v.region, v.revision, v.status);
    });
    g._blob = normalize(parts.filter(Boolean).join(' '));
    return g._blob;
  }

  function getFiltered() {
    if (lib.cache) return lib.cache;
    var tokens = normalize(lib.q).split(' ').filter(Boolean);

    var list = GAMES.filter(function (g) {
      if (lib.platform !== 'all' && g.platform !== lib.platform) return false;

      if (lib.genre !== 'all') {
        if (lib.genre === 'Not verified') {
          if (g.genre) return false;
        } else if (g.genre !== lib.genre) {
          return false;
        }
      }

      if (lib.decade !== 'all') {
        if (lib.decade === 'unknown') {
          if (g.year) return false;
        } else if (!g.year || String(Math.floor(g.year / 10) * 10) !== lib.decade) {
          return false;
        }
      }

      if (tokens.length) {
        var blob = searchBlob(g);
        for (var i = 0; i < tokens.length; i++) {
          if (blob.indexOf(tokens[i]) === -1) return false;
        }
      }
      return true;
    });

    list.sort(SORTERS[lib.sort] || SORTERS['title-asc']);
    lib.cache = list;
    return list;
  }

  function decadesPresent() {
    var seen = {};
    GAMES.forEach(function (g) {
      if (g.year) seen[String(Math.floor(g.year / 10) * 10)] = true;
      else seen.unknown = true;
    });
    return Object.keys(seen).sort();
  }

