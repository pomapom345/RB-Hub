  function renderResults() {
    var results = document.getElementById('results');
    if (!results) return;

    var list = getFiltered();
    var shown = Math.min(lib.shown, list.length);
    var visible = list.slice(0, shown);

    if (!list.length) {
      results.innerHTML = '<div class="state-panel">' +
        '<span class="state-art">' + icon('search', 34) + '</span>' +
        '<h3>No games match that search</h3>' +
        '<p>Try a shorter query, a ROM filename such as <code>DKONG</code>, or clear one of the active filters.</p>' +
        '<button class="btn btn--primary btn--sm" type="button" data-clear="all">Reset all filters</button>' +
        '</div>';
    } else {
      results.innerHTML = '<div class="game-grid">' + visible.map(gameCard).join('') + '</div>';
    }

    var count = document.getElementById('res-count');
    if (count) {
      var from = list.length ? 1 : 0;
      count.innerHTML = 'Showing <b>' + fmt(from) + '\u2013' + fmt(shown) + '</b> of <b>' + fmt(list.length) +
        '</b> ' + plural(list.length, 'game') +
        (lib.q ? ' for <span class="query">\u201c' + esc(lib.q) + '\u201d</span>' : '');
    }
    var sortLabel = document.getElementById('res-sort');
    if (sortLabel) sortLabel.textContent = 'Sorted: ' + SORT_LABELS[lib.sort];

    var more = document.getElementById('more-row');
    if (more) {
      var remaining = list.length - shown;
      more.innerHTML = remaining > 0
        ? '<button class="btn btn--primary" type="button" data-more="1">Load ' + Math.min(PAGE_SIZE, remaining) +
          ' more (' + fmt(remaining) + ' left) ' + icon('arrow', 13) + '</button>'
        : (list.length > PAGE_SIZE ? '<span class="load-more-note">End of results.</span>' : '');
    }

    var tabs = document.querySelectorAll('#platform-tabs [data-platform]');
    tabs.forEach(function (tab) {
      tab.setAttribute('aria-pressed', tab.getAttribute('data-platform') === lib.platform ? 'true' : 'false');
    });

    renderPills();

    var input = document.getElementById('q');
    if (input) {
      var clearBtn = document.getElementById('clear-q');
      var hint = document.getElementById('search-hint');
      if (clearBtn) clearBtn.hidden = !lib.q;
      if (hint) hint.classList.toggle('hide', !!lib.q);
    }
  }

  function libMutate(fn) {
    fn();
    lib.shown = PAGE_SIZE;
    lib.cache = null;
    syncLibHash();
    renderResults();
  }

  function initLibrary() {
    var input = document.getElementById('q');
    if (input && lib.focusSearch) {
      input.focus();
      input.select();
    }

    if (input) {
      var timer = null;
      input.addEventListener('input', function () {
        var value = input.value;
        lib.q = value;
        lib.cache = null;
        var clearBtn = document.getElementById('clear-q');
        var hint = document.getElementById('search-hint');
        if (clearBtn) clearBtn.hidden = !value;
        if (hint) hint.classList.toggle('hide', !!value);
        clearTimeout(timer);
        timer = setTimeout(function () {
          lib.shown = PAGE_SIZE;
          syncLibHash();
          renderResults();
        }, 170);
      });
      input.addEventListener('keydown', function (e) {
        if (e.key === 'Escape') {
          input.value = '';
          lib.q = '';
          lib.cache = null;
          syncLibHash();
          renderResults();
        }
      });
    }

    var genre = document.getElementById('genre');
    if (genre) genre.addEventListener('change', function () { libMutate(function () { lib.genre = genre.value; }); });

    var decade = document.getElementById('decade');
    if (decade) decade.addEventListener('change', function () { libMutate(function () { lib.decade = decade.value; }); });

    var sort = document.getElementById('sort');
    if (sort) sort.addEventListener('change', function () { libMutate(function () { lib.sort = sort.value; }); });

    var reset = document.getElementById('reset-all');
    if (reset) reset.addEventListener('click', function () {
      libReset();
      syncLibHash();
      renderResults();
      if (input) { input.value = ''; input.focus(); }
      var g = document.getElementById('genre'); if (g) g.value = 'all';
      var d = document.getElementById('decade'); if (d) d.value = 'all';
      var s = document.getElementById('sort'); if (s) s.value = 'title-asc';
    });

    var toggle = document.getElementById('filters-toggle');
    if (toggle) toggle.addEventListener('click', function () {
      var filters = document.getElementById('filters');
      if (!filters) return;
      var open = filters.classList.toggle('is-open');
      toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
    });

    renderResults();
  }

  function handleLibraryClick(target) {
    var tab = target.closest('[data-platform]');
    if (tab && tab.closest('#platform-tabs')) {
      libMutate(function () { lib.platform = tab.getAttribute('data-platform'); });
      return true;
    }
    var more = target.closest('[data-more]');
    if (more) {
      lib.shown += PAGE_SIZE;
      renderResults();
      return true;
    }
    var clear = target.closest('[data-clear]');
    if (clear) {
      var key = clear.getAttribute('data-clear');
      libMutate(function () {
        if (key === 'all') { libReset(); }
        else if (key === 'q') { lib.q = ''; }
        else if (key === 'platform') { lib.platform = 'all'; }
        else if (key === 'genre') { lib.genre = 'all'; }
        else if (key === 'decade') { lib.decade = 'all'; }
      });
      var input = document.getElementById('q');
      if (input) input.value = lib.q;
      var g = document.getElementById('genre'); if (g) g.value = lib.genre;
      var d = document.getElementById('decade'); if (d) d.value = lib.decade;
      var s = document.getElementById('sort'); if (s) s.value = lib.sort;
      return true;
    }
    return false;
  }

